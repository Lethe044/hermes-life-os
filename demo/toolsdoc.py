"""
Hermes Life OS - tool reference generator
===========================================
Builds docs/TOOLS.md from the tool schemas the agent actually uses, so the
reference can never drift from the code (a test regenerates it and compares).

    python demo/toolsdoc.py          # rewrite docs/TOOLS.md
    python demo/toolsdoc.py --check  # exit 1 when the file is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Dict, List

HEADING = {"tasks": "Tasks", "body": "Body metrics", "subscriptions": "Subscriptions", "people": "People and birthdays",
           "agenda": "Today's agenda", "lists": "Lists", "savings": "Savings goals", "symptoms": "Symptoms", "notes": "Notes",
           "income": "Income", "debts": "Debts", "countdowns": "Countdowns", "supplies": "Supplies",
           "timeblocks": "Time blocks", "okrs": "Objectives", "recipes": "Recipes and meal plan", "trips": "Trips",
           "finder": "Search", "closing": "Closing summary", "repair_hints": "Data repair", "chores": "Chores",
           "expiries": "Expiry dates", "routines": "Routines", "gifts": "Gift ideas", "decisions": "Decision journal",
           "weekahead": "Week ahead", "trash": "Recently deleted", "recledger": "Recommendation ledger",
           "backup": "Backup pins", "priorities": "Daily priorities", "planday": "Plan my day", "wheel": "Life wheel",
           "library": "Library", "calendar_export": "Calendar export", "inbox": "Inbox",
           "weekly_review": "Weekly review", "flashcards": "Flashcards",
           "networth": "Net worth", "projects": "Projects",
           "waiting": "Waiting for"}


def _first_sentence(text: str, limit: int = 170) -> str:
    text = " ".join(str(text).split())
    cut = text.find(". ")
    if 0 < cut < limit:
        text = text[:cut + 1]
    if len(text) > limit:
        text = text[:limit - 3].rstrip() + "..."
    return text.replace("|", "/")


def _params(schema: Dict[str, Any]) -> str:
    fn = schema["function"]["parameters"]
    req = set(fn.get("required", []))
    names = [f"`{k}`{'*' if k in req else ''}" for k in fn.get("properties", {})]
    return ", ".join(names) if names else "none"


def render() -> str:
    demo = str(Path(__file__).resolve().parent)
    if demo not in sys.path:
        sys.path.insert(0, demo)
    import planner_schemas as ps
    import tools
    plugin = {s["function"]["name"] for s in getattr(tools, "PLUGIN_TOOLS", [])}
    groups: Dict[str, List[Dict[str, Any]]] = {}
    for s in tools.TOOLS:
        name = s["function"]["name"]
        if name in plugin:
            continue
        groups.setdefault(ps.TOOL_MODULES.get(name, "core"), []).append(s)
    total = sum(len(v) for v in groups.values())
    out = ["# Tool reference", "",
           f"Every tool the agent can call ({total} in total). Generated by `python demo/toolsdoc.py`; do not edit by hand.",
           "A `*` marks a required parameter. Tools from your own plugins are not listed here.", ""]
    order = ["core"] + [m for m in HEADING if m in groups]
    order += sorted(m for m in groups if m not in order)
    for module in order:
        rows = groups.get(module)
        if not rows:
            continue
        out += [f"## {'Tracking, memory and insights' if module == 'core' else HEADING.get(module, module)} ({len(rows)})", "",
                "| Tool | What it does | Parameters |", "| --- | --- | --- |"]
        for s in rows:
            f = s["function"]
            out.append(f"| `{f['name']}` | {_first_sentence(f.get('description', ''))} | {_params(s)} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: List[str]) -> int:
    path = Path(__file__).resolve().parent.parent / "docs" / "TOOLS.md"
    text = render()
    if "--check" in argv:
        return 0 if path.exists() and path.read_text(encoding="utf-8") == text else 1
    path.write_text(text, encoding="utf-8")
    print(f"Wrote {path} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
